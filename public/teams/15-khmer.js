/* ---- scoring ---- */
function khTestScore_(T){
  var part=function(name){ var r=0, of=0, pr=0, pm=0; T.qs.forEach(function(q){ if(q.part!==name) return; of++; pm+=q.pts; if(q.got){ r++; pr+=q.pts; } }); return { right:r, of:of, pts:pr, max:pm }; };
  var w=part('words'), s=part('sentences'), sc=part('script');
  var speak=Object.keys(T.can).filter(function(k){ return T.can[k]; }).length;
  var testPct = (w.max+s.max) ? (w.pts+s.pts)/(w.max+s.max)*100 : 0;
  var pct=Math.round(testPct*0.75 + speak/KH_CAN.length*100*0.25);
  var level = pct<25 ? 'start' : pct<45 ? 'beginner' : pct<65 ? 'elementary' : pct<82 ? 'intermediate' : 'confident';
  var out={ level:level, pct:pct, speak:speak, words:{ right:w.right, of:w.of }, sentences:{ right:s.right, of:s.of } };
  if(sc.of){ out.script={ right:sc.right, of:sc.of }; out.scriptLevel = sc.right<=2 ? 'none' : sc.right<=5 ? 'some' : 'reads'; }
  return out;
}
